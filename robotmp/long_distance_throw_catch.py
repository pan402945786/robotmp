"""Explore a horizontal long-distance throw/catch using only current observations.

The short vertical skill is used for acquisition and contact verification.  The
launch is generated by a bounded IK trajectory; the object is never teleported
and no flight trajectory from an earlier run is fed to the controller.
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

from .models import Skill
from .skills import SkillStore
from .throw_catch_online import run_trial

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets/skills/short_vertical_throw_catch_50mm.json"
OUTPUT = ROOT / "docs/long_distance_throw_catch_20261021"
SKILL_PATH = ROOT / "assets/skills/long_distance_throw_catch_50mm.json"
MIN_RANGE_M = .10


def make_parameters(dx: float, *, duration: float, speed_x: float, speed_z: float,
                    dy: float = 0.0, speed_y: float = 0.0,
                    close_lead: float = .16) -> dict:
    source = json.loads(SOURCE.read_text(encoding="utf-8"))[0]
    parameters = dict(source["parameters"])
    parameters["stationary_catch"] = False
    parameters["descent_servo"] = True
    # The moving throw has a larger horizontal component; the collision
    # re-enable clearance gate still proves physical separation before contact.
    # The controller may begin causal tracking as soon as four fresh frames are
    # available instead of waiting for the short-throw vertical separation gate.
    parameters["require_observed_separation"] = False
    parameters["enable_collision_after_observed_separation"] = False
    parameters["enable_collision_on_predicted_descent"] = True
    parameters["disable_geometric_collision_enable"] = True
    parameters["enable_collision_descent_distance_m"] = .25
    parameters["collision_enable_min_flight_s"] = .18
    parameters["observed_separation_m"] = .06
    parameters["servo_start_distance_m"] = .35
    parameters["servo_close_distance_m"] = .085
    parameters["servo_position_gain"] = 12.0
    parameters["servo_acceleration_rad_s2"] = 40.0
    parameters["close_lead_s"] = close_lead
    parameters["launch_profile"] = {
        "release_gate": 1.00,
        "pre_spin": False,
        "vertical_toss": {
            "duration_s": duration,
            "speed_x_m_s": speed_x,
            "speed_y_m_s": speed_y,
            "speed_m_s": speed_z,
            "x_m": .55,
            "y_m": 0.0,
            "start_z_m": 1.12,
            "goal_x_m": .55 + dx,
            "goal_y_m": dy,
            "goal_z_m": 1.35,
            "max_horizontal_m_s": 2.5,
        },
    }
    return parameters


def scenario(seed: int, *, noise: float = 0.0, latency: float = 0.0,
             drop: float = 0.0, drag: float | None = None) -> dict:
    result = dict(seed=seed, cube_size_m=.05, release_gate=1.00,
                  sensor_hz=60, noise_m=noise, latency_s=latency,
                  drop_rate=drop, pre_spin=False)
    if drag is not None:
        result["drag"] = drag
    return result


def distance_metrics(report: dict) -> dict:
    release = report.get("release_position")
    closest = report.get("closest_descending") or {}
    cube = closest.get("cube")
    if not release or not cube:
        return {"horizontal_release_to_closest_m": None,
                "horizontal_release_to_closest_x_m": None,
                "catch_target_reached": False}
    dx = float(cube[0]) - float(release[0])
    dy = float(cube[1]) - float(release[1])
    distance = math.hypot(dx, dy)
    return {"horizontal_release_to_closest_m": distance,
            "horizontal_release_to_closest_x_m": dx,
            "catch_target_reached": distance >= MIN_RANGE_M}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument("--trials-per-config", type=int, default=3)
    parser.add_argument("--clean", action="store_true",
                        help="repeat independent clean trials for scoped validation")
    args = parser.parse_args()
    if args.trials_per_config < 1 or args.trials_per_config > 6:
        parser.error("--trials-per-config must be between 1 and 6")
    output = args.output.resolve()
    output.relative_to(ROOT)
    if (output / "summary.json").exists():
        parser.error("choose a new output directory")
    output.mkdir(parents=True, exist_ok=True)

    # Start below the success threshold and increase only the horizontal
    # endpoint/speed.  This makes failures attributable to range and timing.
    configs = [
        ("range_y010", .00, .60, 0.0, 1.20, .10, .30),
        ("range_y015", .00, .80, 0.0, 1.20, .15, .20),
        ("range_y020", .00, .80, 0.0, 1.50, .20, .18),
    ]
    reports = []
    config_results = []
    for config_name, dx, duration, speed_x, speed_z, dy, close_lead in configs:
        params = make_parameters(dx, duration=duration, speed_x=speed_x,
                                 speed_z=speed_z, dy=dy,
                                 speed_y=(.6 if config_name == "range_y010" else .8),
                                 close_lead=close_lead)
        local = []
        for index in range(args.trials_per_config):
            seed = 21000 + len(reports)
            # First trial is clean; later trials add the same observation
            # impairments already covered by the verified short skill.
            if args.clean or index == 0:
                scene = scenario(seed)
            elif index == 1:
                scene = scenario(seed, noise=.001, latency=1/60, drop=.05, drag=.06)
            else:
                scene = scenario(seed, noise=.002, latency=2/60, drop=.10, drag=.025)
            scene.update(params["launch_profile"])
            label = f"{config_name}_{index + 1:02d}"
            report = run_trial(params, scene, output, label)
            report["long_distance_metrics"] = distance_metrics(report)
            report["config_name"] = config_name
            report["target_horizontal_m"] = dx
            local.append(report)
            reports.append(report)
            (output / f"{label}.json").write_text(
                json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
        config_results.append({"config": config_name, "target_horizontal_m": dx,
                               "reports": local,
                               "successes": sum(bool(r.get("complete_success") and
                                                    r.get("long_distance_metrics", {}).get("catch_target_reached"))
                                                for r in local)})
        # A first complete range result is enough to repeat that exact
        # parameter set; keep the later sweep for diagnosis if it fails.
        if config_results[-1]["successes"] == args.trials_per_config:
            break

    successful = [r for r in reports if r.get("complete_success") and
                  (r.get("long_distance_metrics", {}).get("horizontal_release_to_closest_m") or 0.0)
                  >= MIN_RANGE_M]
    validation_complete = len(successful) >= 3
    selected = successful[-1] if successful else (reports[-1] if reports else None)
    params = make_parameters(selected.get("target_horizontal_m", .20), duration=.28,
                             speed_x=1.0, speed_z=1.8) if selected else make_parameters(.20, duration=.28, speed_x=1.0, speed_z=1.8)
    if selected:
        # Preserve the exact launch profile from the measured report.
        params = selected.get("controller_parameters", params)
    skill = {
        "skill_id": "long_distance_throw_catch_50mm_v1",
        "name": "contact_checked_long_distance_throw_catch_50mm",
        "status": "verified" if validation_complete else "candidate",
        "version": 1,
        "task": "long_distance_throw_catch_50mm",
        "object_types": ["cube"],
        "trigger_conditions": ["cube_edge_m == 0.05", "initial_bilateral_contact_verified",
                                "pre_release_finger_geometry_passed", "fresh_timestamped_position_observations",
                                f"horizontal_throw_range_m >= {MIN_RANGE_M:.2f}"],
        "facts": ["short_vertical_skill_provides_contact_checked_acquisition",
                  "horizontal_launch_must_be_generated_by_bounded_arm_trajectory",
                  "catch_success_requires_bilateral_contact_and_uninterrupted_hold",
                  "online_controller_uses_only_delivered_observations_and_joint_encoders"],
        "hypotheses": ["longer_range_needs_more_descent_servo_margin",
                       "horizontal_range_is_limited_by_workspace_and_release_speed"],
        "prediction_correction": ["reuse_measured_grasp_offset_after_each_acquisition",
                                   "wait_for_observed_separation_before_tracking",
                                   "replan_from_timestamped_position_history",
                                   "switch_from_ballistic_intercept_to_contact_braking"],
        "recovery": ["block_release_without_measured_lift_and_geometry",
                     "stop_or_brake_when_observations_are_stale",
                     "retain_candidate_status_until_three_complete_long_range_trials",
                     "record_range_and_contact_failures_separately"],
        "prerequisite_skill_ids": ["short_vertical_throw_catch_50mm_v1"],
        "parameters": params,
        "validation_trials": len(successful),
        "validation_success_rate": len(successful) / len(reports) if reports else 0.0,
        "validation_metrics": {"complete_three_trial_validation": validation_complete,
                                "minimum_horizontal_range_m": min((r["long_distance_metrics"]["horizontal_release_to_closest_m"]
                                                                    for r in successful), default=0.0),
                                "max_hold_duration_s": max((r.get("continuous_hold_duration_s", 0.0)
                                                             for r in successful), default=0.0),
                                "scope": "PyBullet xArm6, 50mm cube, bounded horizontal launch"},
    }
    SKILL_PATH.write_text(json.dumps([skill], ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    summary = {"goal_achieved": validation_complete, "reports": reports,
               "config_results": config_results, "new_skill": skill,
               "source_skill": str(SOURCE.relative_to(ROOT))}
    (output / "summary.json").write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps({"goal_achieved": validation_complete, "successes": len(successful),
                      "reports": len(reports), "skill": str(SKILL_PATH)}, ensure_ascii=False), flush=True)
    return 0 if validation_complete else 2


if __name__ == "__main__":
    raise SystemExit(main())
